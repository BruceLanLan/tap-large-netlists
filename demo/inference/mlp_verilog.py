"""Writes rtl/mlp_digits.v, the circuit of the integer model in model/weights.json (standard library only).

    python3 mlp_verilog.py        # rewrites rtl/mlp_digits.v (deterministic)

The weights are two read-only memories (w1: 64 rows of 16 int8 lanes, w2: 16 rows of 16 lanes, lanes 10..15 zero),
which tools/verilog2tapnet turns into ROM records; the biases are constants. The schedule is the one mlp_model.py
mirrors; see the docstring there and the comments in the generated file.
"""
from __future__ import annotations

import os

from mlp_model import ACC_BITS, LANES, N_HIDDEN, N_IN, N_OUT, load_weights

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "rtl", "mlp_digits.v")


def row_literal(vals) -> str:
    """16 int8 lanes as a 128-bit hex literal, lane j at bits [8j+7:8j]."""
    v = 0
    for j, x in enumerate(vals):
        v |= (x & 0xFF) << (8 * j)
    return f"128'h{v:032x}"


def bias_literal(vals) -> str:
    """16 lanes of 20-bit two's complement as one 320-bit hex literal, lane j at bits [20j+19:20j]."""
    v = 0
    for j, x in enumerate(vals):
        v |= (x & ((1 << ACC_BITS) - 1)) << (ACC_BITS * j)
    return f"320'h{v:080x}"


def generate(w: dict) -> str:
    assert w["nIn"] == N_IN and w["nHidden"] == N_HIDDEN and w["nOut"] == N_OUT and w["lanes"] == LANES
    assert w["accBits"] == ACC_BITS
    w1_rows = [[w["w1"][j][k] for j in range(LANES)] for k in range(N_IN)]
    w2_rows = [[w["w2"][j][i] if j < N_OUT else 0 for j in range(LANES)] for i in range(N_HIDDEN)]
    b1 = list(w["b1"])
    b2 = [w["b2"][j] if j < N_OUT else 0 for j in range(LANES)]
    init1 = "\n".join(f"    w1[{k}] = {row_literal(r)};" for k, r in enumerate(w1_rows))
    init2 = "\n".join(f"    w2[{i}] = {row_literal(r)};" for i, r in enumerate(w2_rows))
    return f"""// Generated by mlp_verilog.py from model/weights.json. Do not edit.
//
// A quantized 64-16-10 MLP for 8 x 8 digits, computed over {N_IN + 1 + N_HIDDEN + N_OUT + 1} beats
// (one beat = one rising edge of clk; tools/verilog2tapnet turns the design into one tapnet/2 file):
//   beats  0..63   L1      acc[j] <= (cnt == 0 ? b1[j] : acc[j]) + x * w1[cnt][j]   for all 16 lanes j
//   beat  64       ACT     h[j]   <= min(15, max(0, acc[j]) >> SHIFT1)
//   beats 65..80   L2      acc[c] <= (cnt == 0 ? b2[c] : acc[c]) + h[cnt] * w2[cnt][c]   (lanes 10..15 are zero)
//   beats 81..90   ARGMAX  if (cnt == 0 || acc[cnt] > best) {{ best <= acc[cnt]; cls <= cnt; }}
//   beat  91       DONE    cls_o = cls, done_o = 1; nothing changes any more
// x is the 4-bit input of the beat: pixel t (min(pixel, 15)) on beats 0..63, zero afterwards. Weights are int8,
// accumulators 20-bit two's complement, inputs and hidden activations 4-bit unsigned. Outputs are the values
// before the clock edge, so the class of the inference is on the outputs of beat 91. All registers start at 0.
module mlp_digits(input clk, input [3:0] x, output [3:0] cls_o, output done_o);
  localparam SHIFT1 = {w["shift1"]};
  localparam [2:0] L1 = 3'd0, ACT = 3'd1, L2 = 3'd2, ARGMAX = 3'd3, DONE = 3'd4;

  reg [2:0] phase = 3'd0;
  reg [5:0] cnt = 6'd0;
  reg [{LANES * ACC_BITS - 1}:0] acc = {LANES * ACC_BITS}'d0;   // 16 lanes x 20 bits, lane j at [20j+19:20j]
  reg [{LANES * 4 - 1}:0] h = {LANES * 4}'d0;                    // 16 hidden activations x 4 bits
  reg [{ACC_BITS - 1}:0] best = {ACC_BITS}'d0;
  reg [3:0] cls = 4'd0;

  // weights: lane j of a row at bits [8j+7:8j]; read-only memories (ROM records a = 6 / a = 4, w = 128)
  reg [127:0] w1 [0:{N_IN - 1}];
  reg [127:0] w2 [0:{N_HIDDEN - 1}];
  initial begin
{init1}
{init2}
  end
  // biases, 20-bit two's complement per lane
  wire [{LANES * ACC_BITS - 1}:0] bias1 = {bias_literal(b1)};
  wire [{LANES * ACC_BITS - 1}:0] bias2 = {bias_literal(b2)};

  wire l1 = phase == L1;
  wire first = cnt == 6'd0;
  wire [127:0] row = l1 ? w1[cnt] : w2[cnt[3:0]];
  wire [3:0] xin = l1 ? x : h[cnt[3:0] * 4 +: 4];
  wire [{LANES * ACC_BITS - 1}:0] bias = l1 ? bias1 : bias2;

  wire [{LANES * ACC_BITS - 1}:0] sums;   // the 16 multiply-accumulates of the beat
  wire [{LANES * 4 - 1}:0] acts;          // the 16 requantized activations
  genvar j;
  generate
    for (j = 0; j < {LANES}; j = j + 1) begin : lane
      wire signed [7:0] wj = row[8 * j +: 8];
      wire signed [12:0] prod = $signed({{1'b0, xin}}) * wj;
      wire [{ACC_BITS - 1}:0] a = acc[{ACC_BITS} * j +: {ACC_BITS}];
      wire [{ACC_BITS - 1}:0] base = first ? bias[{ACC_BITS} * j +: {ACC_BITS}] : a;
      assign sums[{ACC_BITS} * j +: {ACC_BITS}] = base + {{{{{ACC_BITS - 13}{{prod[12]}}}}, prod}};
      wire [{ACC_BITS - 1}:0] relu = a[{ACC_BITS - 1}] ? {ACC_BITS}'d0 : a;
      wire [{ACC_BITS - 1}:0] sh = relu >> SHIFT1;
      assign acts[4 * j +: 4] = (|sh[{ACC_BITS - 1}:4]) ? 4'hf : sh[3:0];
    end
  endgenerate

  wire [{ACC_BITS - 1}:0] cur = acc[cnt[3:0] * {ACC_BITS} +: {ACC_BITS}];
  wire upd = first | ($signed(cur) > $signed(best));

  always @(posedge clk) begin
    case (phase)
      L1: begin
        acc <= sums;
        if (cnt == 6'd{N_IN - 1}) begin phase <= ACT; cnt <= 6'd0; end else cnt <= cnt + 6'd1;
      end
      ACT: begin
        h <= acts;
        phase <= L2;
        cnt <= 6'd0;
      end
      L2: begin
        acc <= sums;
        if (cnt == 6'd{N_HIDDEN - 1}) begin phase <= ARGMAX; cnt <= 6'd0; end else cnt <= cnt + 6'd1;
      end
      ARGMAX: begin
        if (upd) begin best <= cur; cls <= cnt[3:0]; end
        if (cnt == 6'd{N_OUT - 1}) phase <= DONE; else cnt <= cnt + 6'd1;
      end
      default: ;
    endcase
  end

  assign cls_o = cls;
  assign done_o = phase == DONE;
endmodule
"""


def main() -> None:
    text = generate(load_weights())
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
